import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

test("static geometry worker bundle matches sources and has no runtime/service dependencies", async () => {
  const result = await build({ absWorkingDir: fileURLToPath(new URL("../", import.meta.url)),
    entryPoints: ["core/geometry/geometry.worker.js"], outfile: "core/geometry/geometry.worker.bundle.js",
    bundle: true, format: "esm", platform: "browser", target: "es2022", minify: true, legalComments: "inline",
    banner: { js: "// Generated by npm run build:geometry-worker. Source: geometry.worker.js. Do not edit." }, write: false, metafile: true });
  assert.equal((await readFile(new URL("../core/geometry/geometry.worker.bundle.js", import.meta.url), "utf8")).replaceAll("\r\n", "\n"), result.outputFiles[0].text);
  const inputs = Object.keys(result.metafile.inputs).join("\n");
  assert.doesNotMatch(inputs, /core\/(?:ai|runtime|handler|resource)\/|threebox|domains\/|stripe|paypal|openverse|polyhaven/i);
  assert.deepEqual(result.metafile.outputs["core/geometry/geometry.worker.bundle.js"].imports, []);
});
